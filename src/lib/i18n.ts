export type UIKey = keyof typeof ui[typeof defaultLang];

/**
 * Hook de traducción — usa en componentes .astro
 * @example const t = useTranslations('en'); t('nav.contacto')
 */
export function useTranslations(lang: Lang) {
  return function t(key: UIKey): string {
    return (ui[lang] as Record<string, string>)[key] ?? (ui[defaultLang] as Record<string, string>)[key] ?? key;
  };
}

/**
 * Detecta el idioma desde la URL de Astro
 */
export function getLangFromUrl(url: URL): Lang {
  const [, lang] = url.pathname.split('/');
  if (lang === 'en') return 'en';
  if (lang === 'pt') return 'pt';
  return 'es';
}

/**
 * Devuelve la URL equivalente en el otro idioma
 */
export function getAlternateUrl(url: URL, targetLang: Lang): string {
  const pathname = url.pathname;
  const currentLang = getLangFromUrl(url);

  if (currentLang === 'es' && targetLang === 'en') {
    // Agrega prefijo /en
    return `/en${pathname}`;
  } else if (currentLang === 'es' && targetLang === 'pt') {
    return `/pt${pathname}`;
  } else if (currentLang === 'en' && targetLang === 'es') {
    // Quita prefijo /en
    return pathname.replace(/^\/en/, '') || '/';
  } else if (currentLang === 'pt' && targetLang === 'es') {
    return pathname.replace(/^\/pt/, '') || '/';
  }
  return pathname;
}
